CREATE OR REPLACE FUNCTION kg_private.prov_lar_kan(p public.kg_provtraning)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select auth.uid() is not null and (
    p.larare = auth.uid()
    or coalesce(public.kg_ar_admin(),false)
    or exists (select 1 from kg_private.grupplarare l where l.user_id = auth.uid() and l.grupp_id = any(p.grupper)))
$function$;

CREATE OR REPLACE FUNCTION kg_private.prov_elev_kan(p public.kg_provtraning, p_uid uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select exists (select 1 from kg_private.klassmedlem m where m.user_id = p_uid and m.klass_id = p.klass_id)
      or exists (select 1 from kg_private.provdeltagare d where d.user_id = p_uid and d.prov_id = p.id)
      or exists (select 1 from kg_private.gruppmedlem g where g.user_id = p_uid and g.grupp_id = any(p.grupper))
$function$;

drop function if exists public.kg_prov_skapa(text,text,text,text[],text[],integer,date,bigint,text);
CREATE OR REPLACE FUNCTION public.kg_prov_skapa(
  p_titel text, p_kurs text, p_spar text, p_omraden text[], p_nivaer text[],
  p_antal integer, p_datum date, p_grupper bigint[], p_kod text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare uid uuid := auth.uid(); v_kod text; v_bas text; n int := 1; v_id bigint; v_titel text; g bigint;
begin
  if uid is null then return jsonb_build_object('ok',false,'code','ej_inloggad'); end if;
  if not kg_private.prov_larare() then return jsonb_build_object('ok',false,'code','larare_kravs'); end if;
  v_titel := regexp_replace(btrim(coalesce(p_titel,'')), '\s+', ' ', 'g');
  if char_length(v_titel) not between 2 and 60 then return jsonb_build_object('ok',false,'code','titel'); end if;
  if coalesce(cardinality(p_omraden),0) = 0 then return jsonb_build_object('ok',false,'code','omraden'); end if;
  if coalesce(cardinality(p_nivaer),0) = 0 or not (p_nivaer <@ array['E','C','A']) then
    return jsonb_build_object('ok',false,'code','nivaer');
  end if;
  if p_antal is null or p_antal not between 5 and 100 then return jsonb_build_object('ok',false,'code','antal'); end if;
  foreach g in array coalesce(p_grupper,'{}') loop
    if not kg_private.lar_har_grupp(g) then return jsonb_build_object('ok',false,'code','okand_grupp'); end if;
  end loop;
  v_bas := upper(regexp_replace(coalesce(nullif(btrim(p_kod),''),v_titel), '[^A-Za-z0-9ÅÄÖåäö-]+', '-', 'g'));
  v_bas := translate(v_bas, 'ÅÄÖ', 'AAO');
  v_bas := btrim(left(regexp_replace(v_bas, '-{2,}', '-', 'g'), 24), '-');
  if char_length(v_bas) < 3 then v_bas := 'PASS-' || to_char(now(),'YYMMDD'); end if;
  v_kod := v_bas;
  while exists (select 1 from public.kg_provtraning where upper(kod) = upper(v_kod))
     or exists (select 1 from public.kg_grupp where upper(kod) = upper(v_kod)) loop
    n := n + 1; v_kod := v_bas || '-' || n;
  end loop;
  insert into public.kg_provtraning(kod,titel,kurs,spar,omraden,nivaer,antal,datum,klass_id,larare,grupper)
  values (v_kod, v_titel, lower(p_kurs), nullif(lower(btrim(coalesce(p_spar,''))),''), p_omraden, p_nivaer,
          p_antal, p_datum, null, uid, coalesce(p_grupper,'{}'))
  returning id into v_id;
  return jsonb_build_object('ok',true,'id',v_id,'kod',v_kod);
end $function$;

CREATE OR REPLACE FUNCTION public.kg_prov_mina()
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare uid uuid := auth.uid();
begin
  if uid is null or not kg_private.prov_larare() then return jsonb_build_object('ok',false,'code','larare_kravs'); end if;
  return jsonb_build_object('ok',true,'prov',coalesce((
    select jsonb_agg(kg_private.prov_json(p, uid) || jsonb_build_object(
             'tranat',(select count(*) from kg_private.provresultat r where r.prov_id=p.id and r.klara>0),
             'egen',p.larare = uid,
             'grupper',(select coalesce(jsonb_agg(jsonb_build_object('id',g.id,'namn',g.namn) order by g.namn),'[]'::jsonb)
                          from public.kg_grupp g where g.id = any(p.grupper)))
           order by p.aktiv desc, p.skapad desc)
      from public.kg_provtraning p
     where p.larare = uid
        or exists (select 1 from kg_private.grupplarare l where l.user_id = uid and l.grupp_id = any(p.grupper))),
    '[]'::jsonb));
end $function$;

CREATE OR REPLACE FUNCTION public.kg_prov_sammanstallning(p_prov bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare uid uuid := auth.uid(); p public.kg_provtraning%rowtype; v_elever int; v_tranat int; v_omr jsonb; v_klara int; v_lista jsonb;
begin
  if uid is null then return jsonb_build_object('ok',false,'code','ej_inloggad'); end if;
  select * into p from public.kg_provtraning where id = p_prov;
  if not found then return jsonb_build_object('ok',false,'code','okand'); end if;
  if not kg_private.prov_lar_kan(p) then return jsonb_build_object('ok',false,'code','larare_kravs'); end if;
  with elever as (
    select m.user_id from kg_private.klassmedlem m
      join public.kg_klass k on k.id = m.klass_id
     where p.klass_id is not null and m.klass_id = p.klass_id and not k.larare
    union select d.user_id from kg_private.provdeltagare d where d.prov_id = p.id
    union select r.user_id from kg_private.provresultat r where r.prov_id = p.id
    union select g.user_id from kg_private.gruppmedlem g where g.grupp_id = any(p.grupper)
  )
  select count(*), coalesce(jsonb_agg(jsonb_build_object(
           'id',e.user_id,'namn',kg_private.anv_namn(e.user_id),
           'klara',coalesce(r.klara,0),'ratt',coalesce(r.ratt,0),
           'dold',exists (select 1 from kg_private.provdold d where d.prov_id = p.id and d.user_id = e.user_id))
         order by kg_private.anv_namn(e.user_id)), '[]'::jsonb)
    into v_elever, v_lista
    from elever e left join kg_private.provresultat r on r.prov_id = p.id and r.user_id = e.user_id;
  select count(*), coalesce(sum(klara),0) into v_tranat, v_klara
    from kg_private.provresultat where prov_id = p.id and klara > 0;
  select coalesce(jsonb_object_agg(o, jsonb_build_object('forsok',f,'ratt',r,'elever',e)), '{}'::jsonb) into v_omr
    from (
      select o.key as o,
             sum(coalesce((o.value->>'f')::int,0)) as f,
             sum(coalesce((o.value->>'r')::int,0)) as r,
             count(*) filter (where coalesce((o.value->>'f')::int,0) > 0) as e
        from kg_private.provresultat res, jsonb_each(res.per_omr) o
       where res.prov_id = p.id
       group by o.key
    ) x;
  return jsonb_build_object('ok',true,'elever',v_elever,'tranat',v_tranat,'uppgifter',v_klara,
                            'omraden',v_omr,'elevlista',v_lista,'prov',kg_private.prov_json(p, uid));
end $function$;

CREATE OR REPLACE FUNCTION public.kg_prov_avsluta(p_prov bigint, p_aktiv boolean DEFAULT false)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare p public.kg_provtraning%rowtype;
begin
  select * into p from public.kg_provtraning where id = p_prov;
  if not found or not kg_private.prov_lar_kan(p) then return jsonb_build_object('ok',false,'code','okand'); end if;
  update public.kg_provtraning set aktiv = coalesce(p_aktiv,false) where id = p_prov;
  return jsonb_build_object('ok',true);
end $function$;

